"use client";

import { ImageIcon, LayoutTemplate, Sparkles } from "lucide-react";
import { type RefObject, useLayoutEffect, useRef, useState } from "react";
import { trackDesignDownload } from "@/components/design/design-analytics";
import { Button } from "@/components/ui/button";
import { generationFileName } from "@/lib/design/download-name";
import { jpegFileName, pngToJpeg, saveBlob } from "@/lib/design/png-to-jpeg";
import type { SerializedGeneration } from "@/lib/design/serialize";
import { DirectionCard, FailedDirectionCard } from "./direction-card";
import type { ImageSource } from "./flow-logic";

/** One place in the results. `id` is the row that fills it, kept for a
 *  failed row too, so either kind can be regenerated by `regenerateOf`.
 *  `generation` is null where the direction did not render. */
export interface DirectionSlot {
  id: string;
  generation: SerializedGeneration | null;
}

/** How sending one design to the team ended, shown on that design's card. */
export type SendNotice =
  | { tone: "sent"; message: string }
  | { tone: "error"; message: string };

const JPG_FAILED = "The JPG couldn't be made. Download the PNG instead.";

export interface DirectionResultsProps {
  slots: DirectionSlot[];
  source: ImageSource | null;
  imageName: string | null;
  regeneratingSlot: number | null;
  regenerateError: { slot: number; message: string } | null;
  /** The design being sent to the design team, so only its card spins. */
  sendingId: string | null;
  /** Keyed by generation id. */
  sendNotices: Record<string, SendNotice>;
  onRegenerate: (slot: number) => void;
  onSendToTeam: (generation: SerializedGeneration) => void;
  onChooseImagery: () => void;
}

async function downloadJpeg(generation: SerializedGeneration): Promise<void> {
  /* Through the authorised download route, not the card's URL: that route
     always lands on the bucket's signed endpoint, whose CORS rules allow the
     app origin to read the bytes back. */
  const res = await fetch(`/api/design/generations/${generation.id}/download`);
  if (!res.ok) throw new Error("download failed");
  const png = await res.blob();
  const size =
    generation.width && generation.height
      ? { width: generation.width, height: generation.height }
      : null;
  const jpeg = await pngToJpeg(png, size);
  saveBlob(jpeg, jpegFileName(generationFileName(generation)));
}

function focusWasDropped(): boolean {
  const active = document.activeElement;
  return (
    !active ||
    active === document.body ||
    active.getAttribute("role") === "dialog"
  );
}

/** A regenerate that succeeds swaps the card for a new one, taking the
 *  focused Regenerate button with it. Focus then lands on the new card, but
 *  only if it was dropped: a user who tabbed elsewhere during the wait keeps
 *  their place. Synchronous, in the commit that removed the button: the
 *  dialog's focus manager checks in a microtask whether focus fell to
 *  <body> and, if so, parks it on the popup, which a screen reader announces
 *  as the whole dialog before the card. Focused here first, it never falls. */
function useFocusRegeneratedSlot(
  grid: RefObject<HTMLDivElement | null>,
  regeneratingSlot: number | null,
) {
  const previous = useRef(regeneratingSlot);
  useLayoutEffect(() => {
    const finished = previous.current;
    previous.current = regeneratingSlot;
    if (finished === null || regeneratingSlot !== null) return;
    const card = grid.current?.querySelector<HTMLElement>(
      `[data-direction-slot="${finished}"]`,
    );
    if (card && !card.contains(document.activeElement) && focusWasDropped()) {
      card.focus();
    }
  }, [grid, regeneratingSlot]);
}

function SourcePill({
  source,
  imageName,
}: {
  source: ImageSource;
  imageName: string | null;
}) {
  return (
    <span className="inline-flex max-w-full items-center gap-1.5 rounded-full bg-[var(--status-progress-bg)] px-2.5 py-1 text-[12px] font-medium text-[var(--status-progress-fg)]">
      {source === "upload" ? (
        <ImageIcon aria-hidden="true" className="size-3.5 shrink-0" />
      ) : (
        <Sparkles aria-hidden="true" className="size-3.5 shrink-0" />
      )}
      <span className="truncate">
        {source === "upload"
          ? `Built around ${imageName ?? "your image"}`
          : "KO-created imagery"}
      </span>
    </span>
  );
}

function EmptyResults({ onChooseImagery }: { onChooseImagery: () => void }) {
  return (
    <div
      className="flex flex-col items-center gap-3 rounded-xl border-2 border-dashed px-6 py-12 text-center"
      style={{ borderColor: "var(--border-control)" }}
    >
      <span className="flex size-11 items-center justify-center rounded-full bg-[rgba(19,139,200,0.15)] text-primary-text">
        <LayoutTemplate aria-hidden="true" className="size-5" />
      </span>
      <div className="flex flex-col gap-1">
        <h3 className="font-display text-[16px] font-bold text-foreground">
          No designs yet
        </h3>
        <p className="max-w-[360px] text-[13px] leading-relaxed text-[var(--text-secondary)]">
          Nothing came back from this run. Pick the imagery again and KO will
          make two fresh directions.
        </p>
      </div>
      <Button type="button" onClick={onChooseImagery}>
        Choose imagery
      </Button>
    </div>
  );
}

export function DirectionResults({
  slots,
  source,
  imageName,
  regeneratingSlot,
  regenerateError,
  sendingId,
  sendNotices,
  onRegenerate,
  onSendToTeam,
  onChooseImagery,
}: DirectionResultsProps) {
  /* Keyed to the design, not one shared flag: converting one card must not
     make the other claim to be working too. */
  const [convertingId, setConvertingId] = useState<string | null>(null);
  const [jpgFailedId, setJpgFailedId] = useState<string | null>(null);
  const grid = useRef<HTMLDivElement>(null);
  useFocusRegeneratedSlot(grid, regeneratingSlot);

  if (slots.length === 0) {
    return <EmptyResults onChooseImagery={onChooseImagery} />;
  }

  const rendered = slots.flatMap((s) => (s.generation ? [s.generation] : []));
  const firstSize =
    rendered[0]?.width && rendered[0]?.height
      ? { width: rendered[0].width, height: rendered[0].height }
      : null;

  async function handleJpeg(generation: SerializedGeneration) {
    setConvertingId(generation.id);
    setJpgFailedId((id) => (id === generation.id ? null : id));
    try {
      await downloadJpeg(generation);
      trackDesignDownload(generation, "jpg");
    } catch {
      setJpgFailedId(generation.id);
    } finally {
      setConvertingId((id) => (id === generation.id ? null : id));
    }
  }

  return (
    <div className="flex flex-col gap-4">
      {source ? (
        <div className="flex">
          <SourcePill source={source} imageName={imageName} />
        </div>
      ) : null}

      <div ref={grid} className="grid gap-4 sm:grid-cols-2">
        {slots.map(({ id, generation }, index) => {
          const regenerate = {
            regenerating: regeneratingSlot === index,
            regenerateBlocked:
              regeneratingSlot !== null && regeneratingSlot !== index,
            regenerateError:
              regenerateError?.slot === index ? regenerateError.message : null,
            onRegenerate: () => onRegenerate(index),
          };
          const notice = sendNotices[id];
          return generation ? (
            <DirectionCard
              key={id}
              generation={generation}
              index={index}
              convertingJpg={convertingId === id}
              onDownloadPng={() => trackDesignDownload(generation, "png")}
              onDownloadJpg={() => void handleJpeg(generation)}
              sendingToTeam={sendingId === id}
              onSendToTeam={() => onSendToTeam(generation)}
              sentMessage={notice?.tone === "sent" ? notice.message : null}
              actionErrors={[
                ...(jpgFailedId === id ? [JPG_FAILED] : []),
                ...(notice?.tone === "error" ? [notice.message] : []),
              ]}
              {...regenerate}
            />
          ) : (
            <FailedDirectionCard
              key={id}
              index={index}
              size={firstSize}
              otherReady={rendered.length > 0}
              {...regenerate}
            />
          );
        })}
      </div>
    </div>
  );
}
