const hidden = (line: string, headline: string) =>
  footerLinesFor({ footerStyle: "text", headline, footerLines: [line] })
    .length === 0;

describe("acceptance: the renderer and the fact writer read repeats as the verifier does", () => {
  it.each(FOOTER_ROWS)("%s: %j under %j", (id, line, headline, kept) => {
    expect(!hidden(line, headline)).toBe(id in FOOTER_KEPT ? true : kept);
  });

  it("keeps on purpose only lines the critics read as repeats", () => {
    for (const id of Object.keys(FOOTER_KEPT)) {
      expect(FOOTER_ROWS.find((r) => r[0] === id)?.[3]).toBe(false);
    }
  });

  /* Round-11 code critic, break 2: the renderer may hide a line only when
     everything it states is stated above it by the verifier's own rule.
     Every fact of the set, against every line the renderer hides: the
     footer rows, and each design's own headline and clauses under copy
     that holds them. */
  it("hides no line that states a fact the copy above does not", () => {
    const facts = [
      ...new Map(
        FACT_ROWS.filter((r) => !r[3]).map((r) => [
          `${r[1]}|${r[2]}`,
          fact(r[1], r[2]),
        ]),
      ).values(),
    ];
    const pairs: [string, string][] = FOOTER_ROWS.map((r) => [r[1], r[2]]);
    for (const row of FACT_ROWS) {
      const above = row[4].headline;
      const clauses = above.split(/\s*[.·;!?]\s+|,\s+/).filter(Boolean);
      for (const line of [above, row[2], ...clauses]) {
        pairs.push(
          [line, above],
          [line, `${above}. Book now`],
          [line, `Hello · ${above}`],
          [line, `${row[2]} · ${above}`],
        );
      }
    }
    const hiddenPairs = [
      ...new Map(pairs.map((p) => [p.join("\u0000"), p])).values(),
    ].filter(([line, above]) => hidden(line, above));
    expect(hiddenPairs.length).toBeGreaterThan(100);
    const wrong = hiddenPairs.flatMap(([line, above]) =>
      facts
        .filter((f) => factStated(f, copy(line)) && !factStated(f, copy(above)))
        .map(
          (f) =>
            `${f.kind} ${JSON.stringify(f.text)}: ${JSON.stringify(line)} under ${JSON.stringify(above)}`,
        ),
    );
    expect(wrong).toEqual([]);
  });

  /* The verifier reads the footer the renderer draws: a footer whose style
     is "none", or a fourth line, is on no design (round-11 code critic,
     J13: a fact was counted from a line the renderer did not draw). */
  it("states nothing from a footer the renderer does not draw", () => {
    const age = fact("age", "Ages 8+");
    const design = (footerStyle: "text" | "none", footerLines: string[]) => ({
      ...copy("Ice cream social"),
      footerLines,
      footerStyle,
    });
    expect(factStated(age, design("text", ["Ages 8+"]))).toBe(true);
    expect(factStated(age, design("none", ["Ages 8+"]))).toBe(false);
    expect(
      factStated(age, design("text", ["Lekki", "Ajah", "Ikoyi", "Ages 8+"])),
    ).toBe(false);
  });

  it.each(REDUNDANT_ROWS)("%s", (_id, design, dropped) => {
    expect(redundantFooterItems(design)).toEqual(dropped);
  });

  /* Round-11 code critic, F1 and F3: a repeat the candidate check finds is
     dropped only when every fact the design stated is still stated. */
  it.each([
    [
      "r11 R1",
      "Fun for all ages · 8+ flavours",
      "Ages: 8+",
      fact("age", "Ages 8+"),
    ],
    [
      "r11 R2",
      "Book your seats · 8 courses",
      "Seats: 8",
      fact("quantity", "8 seats"),
    ],
  ] as const)("%s: keeps %j under %j", (_id, headline, item, f) => {
    const design = {
      ...copy(headline, "", "", [item]),
      footerStyle: "text" as const,
    };
    expect(factStated(f, design)).toBe(true);
    expect(droppedSafely(design, item, [f])).toBeNull();
  });
});
